function [err, cross, sim, spec] = defense_error(mf, mexit, angleDeg, targetX, targetY, dt)
% Simulates defense missile launched from x=50 km back toward x=49 km.

spec = struct( ...
    'Mi',70, ...
    'Mf',mf, ...
    'Cd',0.45, ...
    'Dref',0.15, ...
    'P0',101325*20, ...
    'T0',2500, ...
    'Dexit',0.13, ...
    'gamma',1.24, ...
    'Rgas',350, ...
    'Mexit',mexit);

sim = simulate_missile(spec, 180-angleDeg, dt, 50e3, 0, 60, false);
cross = interpolate_crossing(sim.x, sim.y, sim.t, targetX);
if isempty(cross)
    err = inf;
else
    err = abs(cross.y - targetY);
end
end
